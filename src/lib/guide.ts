function foldFor(place: PlaceId, priority: PriorityId, garment: GarmentId) {
  if (place === "hang") {
    return {
      foldId: "hang",
      foldName: "Навес с люверсом",
      foldWhy: "Вшив не нужен: ярлык вешают на биркодержатель. Форму и плотность подберём под изделие.",
    };
  }
  if (place === "side" || garment === "kids" || garment === "outer") {
    return {
      foldId: "flag",
      foldName: "Флаг",
      foldWhy: "Свободный край не трёт кожу и не мешает в носке. Для детского, верха и бокового шва это самый спокойный сгиб.",
    };
  }
  if (place === "accent" || (garment === "premium" && priority === "status")) {
    return {
      foldId: "volume",
      foldName: garment === "premium" && place === "neck" ? "Стандарт плотнее обычного" : "Объём или короткий стандарт",
      foldWhy:
        place === "accent"
          ? "На кармане и поясе короткая бирка читается лучше длинной петельки."
          : "Для костюма и пальто плотность важнее мягкости: логотип должен держать форму.",
    };
  }
  if (priority === "soft" || garment === "basic") {
    return {
      foldId: "loop",
      foldName: "Петелька",
      foldWhy: "Сгиб по центру даёт две стороны и аккуратный вшив на горловине. Если не уверены — начинайте с петельки.",
    };
  }
  return {
    foldId: "standard",
    foldName: "Стандарт",
    foldWhy: "Прямой край понятен швее и подходит большинству изделий. Если цех уже шьёт «как обычно» — не меняйте конструкцию без причины.",
  };
}

