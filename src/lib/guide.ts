function foldFor(place: PlaceId, priority: PriorityId, garment: GarmentId) {
  if (place === "hang") {
    return {
      foldId: "hang",
      foldName: "Навес с люверсом",
      foldWhy: "Вшив не нужен: ярлык вешают на биркодержатель. Форму и плотность подберём под изделие.",
    };
  }
  if (place === "side" || garment === "kids" || garment === "outer") {
    return {
      foldId: "sides",
      foldName: "Подгибка с двух сторон",
      foldWhy: "Края подогнуты, срез не торчит. Для бокового шва, детского и верха это спокойная посадка.",
    };
  }
  if (place === "accent" || (garment === "premium" && priority === "status")) {
    return {
      foldId: "butterfly",
      foldName: "Подгибка бабочка",
      foldWhy: "Концы подогнуты внутрь. На кармане, поясе и акценте срез спрятан.",
    };
  }
  if (priority === "soft" || garment === "basic") {
    return {
      foldId: "center",
      foldName: "Сгиб по центру",
      foldWhy: "Лента складывается по центру. Свободные края добавляем, если они нужны швее.",
    };
  }
  return {
    foldId: "straight",
    foldName: "Прямой рез",
    foldWhy: "Без свободных краёв и подгибок. Если цех уже шьёт «как обычно» — начните с прямого реза.",
  };
}

