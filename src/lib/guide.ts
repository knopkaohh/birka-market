export function guideComment(result: GuideResult, answers: GuideAnswers) {
  const garment = garmentOptions.find((item) => item.id === answers.garment)?.label;
  const place = placeOptions.find((item) => item.id === answers.place)?.label;
  return `Подбор с /kak-vybrat: ${result.title}. Изделие: ${garment}. Место: ${place}. Сгиб: ${result.foldName}. Тираж ориентир: ${result.qty}.`;
}
