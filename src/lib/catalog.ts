export function catalogByMaterial(material: string) {
  return catalogItems.filter((item) => item.material === material);
}

export function getCatalogItem(material: string, path: string) {
  return catalogItems.find((item) => item.material === material && (item.path === path || item.uid === path));
}

export function catalogHref(item: CatalogItem) {
  return `/${item.material}/tproduct/${item.path}`;
}

export function lowestQuote<T extends { price: string }>(quotes: T[]) {
  const ranked = quotes
    .map((quote) => ({
      quote,
      value: Number(quote.price.replace(/\s/g, "").replace(",", ".").replace(/[^\d.]/g, "")),
    }))
    .filter((item) => Number.isFinite(item.value) && item.value > 0)
    .sort((a, b) => a.value - b.value);
  return ranked[0]?.quote ?? quotes[0];
}

export function catalogOrderHref(
  item: CatalogItem,
  quote?: { qty: string; size: string; spec: string; time: string; price: string },
) {
  const params = new URLSearchParams();
  if (quote) {
    const qty = quote.qty.replace(/\D/g, "");
    if (qty) params.set("qty", qty);
    params.set("size", quote.size);
    params.set("spec", quote.spec);
    params.set("time", quote.time);
    params.set("price", quote.price);
  }
  params.set("example", item.title);
  return `${catalogHref(item)}?${params.toString()}#zakaz`;
}

